// Wiki Exporter — compact media descriptions and optional media hyperlinks.
// All work is on the inert article DOM; nothing is fetched or embedded.
const WikiMedia = (() => {
    const modes = Object.freeze(["captions", "retain"]);
    const labels = Object.freeze({captions:"Captions and descriptions only",retain:"Retain media links"});
    const normalize = mode => modes.includes(mode) ? mode : "captions";
    const protectedSelector = '.references,.reference,.mw-references-wrap,.reflist,.citation,.cite,.mw-cite-backlink,cite,[role="doc-biblioref"],[role="doc-noteref"],[role="doc-backlink"],[role="doc-endnotes"],[role="doc-footnote"],.license-description,.license,[rel~="license"]';
    const gallerySelector = '.gallery,.wikia-gallery,.mw-gallery,.gallerybox,.wikia-gallery-item,.gallery-item,.mw-gallery-item';
    const itemSelector = '.gallerybox,.wikia-gallery-item,.gallery-item,.mw-gallery-item,figure';
    const captionSelector = '.gallerytext,.gallery-text,.gallery-caption,.wikia-gallery-caption,.lightbox-caption,.thumbcaption,figcaption';
    function safeURL(value,base) {
        if(typeof value!=="string"||!value.trim()) return null;
        try {const u=new URL(value,base);return ["http:","https:"].includes(u.protocol)&&!u.username&&!u.password?u:null;}catch{return null;}
    }
    function decode(value){try{return decodeURIComponent(value);}catch{return value;}}
    function mediaKind(u) {
        if(!u)return null;
        const path=decode(u.pathname);
        if(u.hostname.endsWith(".fandom.com")&&path.startsWith("/wiki/")) {
            const title=path.slice(6).replaceAll("_"," ");
            // Preserve explicit history and revision destinations.
            if(u.searchParams.has("oldid")||u.searchParams.get("action")==="history")return null;
            if(/^(File|Image|Media):|^Special:FilePath\//i.test(title))return "image";
            if(/\/(?:gallery|image gallery)(?:\/|$)/i.test(title))return "gallery";
        }
        if(/(^|\.)(?:wikia\.nocookie\.net|images\.wikia\.com)$/i.test(u.hostname)||/\.(?:jpe?g|png|gif|webp|avif|svg|bmp|tiff?|ico)(?:\/|$)/i.test(path))return "image";
        return null;
    }
    function protectedLink(a,u) {
        if(a.closest(protectedSelector)||a.matches('.reference-text,.external.autonumber'))return true;
        if(u&&(/(^|\.)creativecommons\.org$/i.test(u.hostname)&&/^\/(licenses|publicdomain)\//i.test(u.pathname)||u.searchParams.get("action")==="history"||u.searchParams.has("oldid")||/^\/wiki\/Special:(?:PermanentLink|PermaLink|Contributions)/i.test(decode(u.pathname))||/^#?(cite_(note|ref)[-_]|ref[-_]|fn[-_])/i.test(decode(u.hash.slice(1)))))return true;
        return false;
    }
    function toSpan(a) {
        const span=document.createElement("span");
        for(const name of ["id","class","lang","dir","title"])if(a.hasAttribute(name))span.setAttribute(name,a.getAttribute(name));
        span.append(...a.childNodes);a.replaceWith(span);
    }
    function normText(s){return String(s??"").replace(/\s+/g," ").trim().toLocaleLowerCase();}
    function apply(root,article,stats) {
        const mode=normalize(article.mediaMode), keep=mode==="retain";
        let omitted=0, removed=0, retained=0;
        const thumbnailAnchors=new Set(), galleryItems=new Set();
        // Only trust media markers generated by this module.
        for(const a of root.querySelectorAll("a[data-wiki-exporter-media]"))a.removeAttribute("data-wiki-exporter-media");
        // Record thumbnail-only wrappers before replacing any images.
        const images=[...root.querySelectorAll("img")];
        for(const image of images) {
            const a=image.closest("a");
            if(a&&!a.textContent.trim())thumbnailAnchors.add(a);
        }
        for(const image of images) {
            if(!root.contains(image))continue;
            const mediaURL=safeURL(image.getAttribute("data-src"),article.url)||safeURL(image.getAttribute("src"),article.url);
            if(mediaURL)stats.imagesWithURL++;
            const wrapper=image.closest("a"), inGallery=Boolean(image.closest(gallerySelector));
            const item=inGallery?image.closest(itemSelector):null;
            if(item)galleryItems.add(item);
            const caption=item?.querySelector(captionSelector)?.textContent.trim()||"";
            let description=(image.getAttribute("alt")||image.getAttribute("title")||"").replace(/\s+/g," ").trim();
            // A raw source URL is not a useful visible caption.
            if(/^https?:\/\/\S+$/i.test(description)||/^(image|thumbnail|photo)$/i.test(description))description="";
            const duplicate=description&&caption&&normText(description)===normText(caption);
            if(!keep&&inGallery&&(!description||duplicate)) {
                image.remove();omitted++;continue;
            }
            const label=description?`[Image: ${description}]`:"[Image]";
            const replacement=document.createElement(keep&&mediaURL&&!wrapper?"a":"span");
            replacement.textContent=label;
            if(keep&&mediaURL&&!wrapper)replacement.setAttribute("href",mediaURL.href);
            if(keep&&wrapper&&thumbnailAnchors.has(wrapper)&&!safeURL(wrapper.getAttribute("href"),article.url)&&mediaURL)wrapper.setAttribute("href",mediaURL.href);
            image.replaceWith(replacement);
        }
        // Also recognize gallery subpages and file links that do not contain a thumbnail.
        for(const a of [...root.querySelectorAll("a")]) {
            const u=safeURL(a.getAttribute("href"),article.url);
            const kind=mediaKind(u);
            if(!kind&&!thumbnailAnchors.has(a)&&!/^\[Image(?:[:\]])/i.test(a.textContent.trim()))continue;
            if(protectedLink(a,u))continue;
            // Never expose a bare CDN URL as the generated hyperlink label.
            if(kind&&/^https?:\/\/\S+$/i.test(a.textContent.trim()))a.textContent=kind==="gallery"?"[Gallery]":"[Image]";
            if(keep&&u) {
                a.setAttribute("data-wiki-exporter-media","true");retained++;continue;
            }
            if(u)removed++;
            if(a.hasAttribute("id")||a.textContent.trim()||a.querySelector("[id]"))toSpan(a);
            else a.remove();
        }
        // Empty thumbnail-only gallery entries should not become empty bullets.
        for(const item of galleryItems) {
            if(root.contains(item)&&!item.textContent.trim()&&!item.querySelector("[id]")&&!item.id)item.remove();
        }
        if(omitted) {
            const note=document.createElement("p");
            note.textContent=`[Gallery note: ${omitted} thumbnail(s) with no additional description omitted; captions and distinct descriptions retained. See the source for images.]`;
            root.append(note);
        }
        stats.mediaLinksRemoved=removed;stats.mediaLinksRetained=retained;stats.galleryThumbnailsOmitted=omitted;
        const warnings=[];
        if(stats.images||removed||retained||omitted)warnings.push(`Media policy: ${labels[mode]}; ${removed} media hyperlink(s) stripped, ${retained} retained, ${omitted} redundant or uncaptioned gallery thumbnail(s) omitted. No image bytes downloaded.`);
        return warnings;
    }
    return {modes,labels,normalize,apply};
})();
